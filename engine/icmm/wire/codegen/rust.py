"""The Rust side: typify's input schema, and the Tauri command files typify doesn't write."""

from __future__ import annotations

import json
from typing import Any

from icmm.wire.codegen.contract import Schema

_DEF = "#/$defs/"
_DEFINITIONS = "#/definitions/"

HEADER = "// @generated by `uv run icmm-wire gen` from engine/icmm/wire. Don't edit.\n"


def typify_schema(schema: Schema) -> Schema:
    """The bundle reshaped for typify: draft-07 `definitions`, and each union's variants inlined.

    typify reads a `oneOf` of `$ref`s as an untagged enum that tries each variant by shape; with
    the variants inline it sees the shared `const` tag and emits `#[serde(tag = "…")]`. A variant
    used nowhere else is dropped, so it isn't also emitted as a lone struct.
    """
    defs: dict[str, Any] = schema["$defs"]
    inlined: set[str] = set()
    out: dict[str, Any] = {}
    for name, node in defs.items():
        if "oneOf" in node:
            variants = []
            for v in node["oneOf"]:
                variant = v["$ref"].removeprefix(_DEF)
                inlined.add(variant)
                # Without the title, typify writes the variant's doc as one line, not a
                # `/**Title\n…*/` block whose indented tail rustdoc runs as a doctest.
                variants.append({k: v for k, v in defs[variant].items() if k != "title"})
            node = {k: v for k, v in node.items() if k != "discriminator"} | {"oneOf": variants}
        out[name] = node
    out = _words_as_enums(out)
    text = json.dumps(out)
    still_used = {n for n in inlined if f'"{_DEF}{n}"' in text}
    out = {n: s for n, s in out.items() if n not in inlined or n in still_used}
    text = json.dumps({"definitions": out}).replace(_DEF, _DEFINITIONS)
    return json.loads(text)


def _words_as_enums(node: Any) -> Any:
    """A union's one fixed string (a dataset step's `"swept"`) as a one-value `enum`: typify
    reads a `const` there as any string, and an `enum` as a type that takes only that word."""
    if isinstance(node, list):
        return [_words_as_enums(n) for n in node]
    if not isinstance(node, dict):
        return node
    out = {k: _words_as_enums(v) for k, v in node.items()}
    for key in ("anyOf", "oneOf"):
        if key in out:
            out[key] = [
                {"type": "string", "enum": [b["const"]]}
                if b.get("type") == "string" and isinstance(b.get("const"), str)
                else b
                for b in out[key]
            ]
    return out


def command_names_rs(manifest: Schema) -> str:
    names = ", ".join(f'"{m["name"]}"' for m in _commands(manifest))
    return (
        HEADER
        + "\n/// The app's Tauri commands: one per registry method the UI calls.\n"
        + "/// `build.rs` turns on Tauri's ACL for each; `capabilities/wire.json` allows each.\n"
        + f"pub const COMMANDS: &[&str] = &[{names}];\n"
    )


def commands_rs(manifest: Schema) -> str:
    commands = _commands(manifest)
    types = sorted({t for m in commands for t in (m["params"], m["result"]) if t})
    out = [
        HEADER,
        "//! The Tauri commands, one per registry method the UI calls, each named like its method.",
        "//! A desktop command's body is `crate::desktop::<name>`, so the compiler holds it to the",
        "//! registry's types.",
        "",
        f"use super::types::{{{', '.join(types)}}};" if types else "",
        "",
        "/// The protocol this app speaks, `major.minor`.",
        f'pub const PROTOCOL_VERSION: &str = "{manifest["protocol"]}";',
        "/// Identifies the wire schema this app was built from.",
        f'pub const SCHEMA_HASH: &str = "{manifest["schema_hash"]}";',
        "/// The longest line either side sends or accepts, its newline included.",
        f"pub const MAX_LINE_BYTES: usize = {manifest['max_line_bytes']};",
        "",
        "/// How long the desktop waits for an agent method's reply; `None` for a desktop command.",
        "pub fn timeout_ms(method: &str) -> Option<u64> {",
        "    match method {",
        *(
            f'        "{m["name"]}" => Some({m["timeout_ms"]}),'
            for m in manifest["methods"]
            if m["timeout_ms"] is not None
        ),
        "        _ => None,",
        "    }",
        "}",
    ]
    for m in commands:
        out += ["", f"/// {m['doc']}", "#[tauri::command]"]
        out += _desktop_command(m) if m["kind"] == "desktop" else _agent_command(m)
    handlers = "".join(f"            crate::wire::commands::{m['name']},\n" for m in commands)
    out += [
        "",
        "/// `tauri::generate_handler!` over every command above.",
        "macro_rules! wire_handler {",
        "    () => {",
        "        ::tauri::generate_handler![",
        handlers.rstrip("\n"),
        "        ]",
        "    };",
        "}",
        "pub(crate) use wire_handler;",
    ]
    return "\n".join(out) + "\n"


def _desktop_command(m: Schema) -> list[str]:
    """Calls its body in `crate::desktop`; a command that declares errors returns a `WireError`."""
    arg = f"params: {m['params']}" if m["params"] else ""
    result = m["result"] or "()"
    if m["errors"]:
        ret = f" -> Result<{result}, crate::wire::types::WireError>"
    else:
        ret = f" -> {result}" if m["result"] else ""
    call = "params" if m["params"] else ""
    fn, wait = ("pub async fn", ".await") if m["async"] else ("pub fn", "")
    body = f"    crate::desktop::{m['name']}({call}){wait}"
    return [f"{fn} {m['name']}({arg}){ret} {{", body, "}"]


def _agent_command(m: Schema) -> list[str]:
    """An async proxy through the active connection, sent again as its kind allows."""
    kind = "crate::connection::policy::Kind::" + ("Write" if m["kind"] == "write" else "Read")
    timeout = f"::std::time::Duration::from_millis({m['timeout_ms']})"
    result = m["result"] or "()"
    if m["params"]:
        arg, call, params = f"params: {m['params']}", "call", "Some(&params)"
    else:
        arg, call, params = "", "call::<(), _>", "None"
    return [
        f"pub async fn {m['name']}({arg}) -> Result<{result}, crate::agent::CallError> {{",
        f'    crate::active::{call}("{m["name"]}", {kind}, {params}, {timeout}).await',
        "}",
    ]


def capability_json(manifest: Schema) -> Schema:
    return {
        "$schema": "../gen/schemas/desktop-schema.json",
        "identifier": "wire",
        "description": (
            "Generated by `uv run icmm-wire gen`: allows every command in the wire registry."
        ),
        "windows": ["main"],
        "permissions": [f"allow-{m['name'].replace('_', '-')}" for m in _commands(manifest)],
    }


def fixture_dispatch_rs(manifest: Schema) -> str:
    """The fixture test's table from (method, part) to the generated type it round-trips through."""
    arms = []
    for m in manifest["methods"]:
        for part, t in (("Params", m["params"]), ("Result", m["result"])):
            rust = t or "()"
            arms.append(f'        ("{m["name"]}", Part::{part}) => roundtrip::<{rust}>(value),')
        if m["event"]:
            arms.append(
                f'        ("{m["name"]}", Part::Event) => roundtrip::<{m["event"]}>(value),'
            )
    return (
        HEADER
        + "\nuse icmm_desktop::wire::types::*;\n\nuse super::{Part, roundtrip};\n\n"
        + "pub fn dispatch(\n    method: &str,\n    part: Part,\n    value: &serde_json::Value,\n"
        + ") -> Result<serde_json::Value, String> {\n    match (method, part) {\n"
        + "\n".join(arms)
        + '\n        _ => Err(format!("{method}: not in the registry")),\n    }\n}\n'
    )


def _commands(manifest: Schema) -> list[Schema]:
    return [m for m in manifest["methods"] if m["command"]]
