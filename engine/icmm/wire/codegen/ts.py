"""The TS side: json-schema-to-typescript's input and output, the commands and the fixtures."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from icmm.wire.codegen.contract import Schema

HEADER = "// @generated by `uv run icmm-wire gen` from engine/icmm/wire. Don't edit.\n"
ROOT_TITLE = "Wire"


def json2ts_schema(schema: Schema) -> Schema:
    """The bundle as json2ts wants it: a titled root, and bare `$ref`s.

    A `$ref` with a sibling (a field's description or default) makes json2ts emit a numbered
    duplicate of the referenced type (`Scheduler1`), so the sibling goes.
    """
    return {"title": ROOT_TITLE, **_bare_refs(schema)}


def _bare_refs(node: Any) -> Any:
    if isinstance(node, list):
        return [_bare_refs(n) for n in node]
    if not isinstance(node, dict):
        return node
    if "$ref" in node:
        return {"$ref": node["$ref"]}
    return {k: _bare_refs(v) for k, v in node.items()}


_ROOT = re.compile(rf"export interface {ROOT_TITLE} \{{\n  \[k: string\]: unknown;\n\}}\n")
_REFERENCED = re.compile(
    rf"( \*\n)? \* This interface was referenced by `{ROOT_TITLE}`'s JSON-Schema\n"
    r' \* via the `definition` "\w+"\.\n'
)
_EMPTY_DOC = re.compile(r"/\*\*\n \*/\n")


def tidy_types(text: str) -> str:
    """json2ts's output without the empty root type and its "referenced by" notes."""
    text = _ROOT.sub("", text)
    text = _REFERENCED.sub("", text)
    text = _EMPTY_DOC.sub("", text)
    return HEADER + "\n" + text


def api_ts(manifest: Schema) -> str:
    commands = [m for m in manifest["methods"] if m["command"]]
    types = sorted({t for m in commands for t in (m["params"], m["result"]) if t})
    out = [
        HEADER,
        'import { invoke } from "@tauri-apps/api/core";',
        f'import type {{ {", ".join(types)} }} from "./types.gen";' if types else "",
        "",
        "/** The protocol this app speaks, `major.minor`. */",
        f'export const PROTOCOL_VERSION = "{manifest["protocol"]}";',
        "/** Identifies the wire schema this app was built from. */",
        f'export const SCHEMA_HASH = "{manifest["schema_hash"]}";',
        "",
        "/** The app's Tauri commands, each named and typed like its registry method. */",
        "export const commands = {",
    ]
    for m in commands:
        result = m["result"] or "void"
        out.append(f"  /** {m['doc']} */")
        if m["params"]:
            out.append(
                f"  {m['name']}: (params: {m['params']}): Promise<{result}> =>\n"
                f'    invoke<{result}>("{m["name"]}", {{ params }}),'
            )
        else:
            out.append(f'  {m["name"]}: (): Promise<{result}> => invoke<{result}>("{m["name"]}"),')
    out += [
        "} as const;",
        "",
        "export type CommandName = keyof typeof commands;",
    ]
    return "\n".join(out) + "\n"


def fixtures_ts(manifest: Schema, fixtures: Path) -> str:
    """Every fixture line as a constant that must `satisfies` its generated type under tsc."""
    out = [
        HEADER,
        "// Each line of wire/fixtures/<method>.ndjson, held to the generated types by tsc.",
        "",
        'import type * as T from "./types.gen";',
        "",
        "export const fixtures = {",
    ]
    for m in manifest["methods"]:
        text = (fixtures / f"{m['name']}.ndjson").read_text(encoding="utf-8")
        lines = [json.loads(line) for line in text.splitlines() if line.strip()]
        params = [line["params"] for line in lines if "method" in line and m["params"]]
        results = [line["result"] for line in lines if "result" in line]
        errors = [line["error"] for line in lines if "error" in line]
        events = [line["event"] for line in lines if "subscription" in line]
        out.append(f"  {m['name']}: {{")
        out.append(_array("params", params, f"T.{m['params']}"))
        out.append(_array("results", results, f"T.{m['result']}" if m["result"] else "null"))
        out.append(_array("errors", errors, "T.WireError"))
        if m["event"]:
            out.append(_array("events", events, f"T.{m['event']}"))
        out.append("  },")
    out.append("};")
    return "\n".join(out) + "\n"


def _array(key: str, values: list[Any], ts_type: str) -> str:
    if not values:
        return f"    {key}: [],"
    items = "".join(f"      {json.dumps(v)} satisfies {ts_type},\n" for v in values)
    return f"    {key}: [\n{items}    ],"


def templates_ts(manifest: Schema) -> str:
    """Each template's preset as a constant typed by tsc: where the desktop starts a protocol."""
    out = [
        HEADER,
        "// Each template's preset, from icmm.dataset.templates: where a protocol made from it",
        "// starts, before its name, source and points. The engine derives a protocol's template",
        "// back from its structure (ADR-0003).",
        "",
        'import type * as T from "./types.gen";',
        "",
        "/** A template a protocol can be made from: every one but `custom`. */",
        'export type TemplateName = Exclude<T.Template, "custom">;',
        "",
        "/** A protocol as a template starts it: everything but its name, source and points. */",
        'export type TemplatePreset = Omit<T.Protocol, "name" | "source" | "points">;',
        "",
        "export const TEMPLATES: Record<TemplateName, TemplatePreset> = {",
    ]
    for name, preset in manifest["templates"].items():
        out.append(f"  {name}: {json.dumps(preset)},")
    out.append("};")
    return "\n".join(out) + "\n"
